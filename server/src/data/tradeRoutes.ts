/**
 * 全球资源贸易运输航线种子数据。
 *
 * 每类资源包含若干条「出口地 → 进口地」运输航线：
 *  - kind ：sea 海运航线 / pipe 油气管道 / land 陆路运输
 *  - value：年贸易流量（单位与 resources.unit 一致），决定连线粗细与粒子密度
 *  - points：途径点 [经度, 纬度]，首点为出口地、末点为进口地；
 *    海运航线途经主要海峡 / 运河（霍尔木兹、马六甲、苏伊士、巴拿马、好望角等），
 *    前端粒子严格沿 points 顺序由出口国流向进口国。
 *
 * 数值为公开统计口径整理的近似示例数据（约 2023 年量级），不代表实时统计发布。
 */

export type TradeRouteKind = 'sea' | 'pipe' | 'land';

export interface TradeRouteSeed {
  from: string; // 出口地（产地 / 出口国 / 港口）
  to: string; // 进口地（消费国 / 港口）
  kind: TradeRouteKind;
  value: number; // 年贸易流量
  points: [number, number][]; // 途径点，首 = 出口，末 = 进口
}

